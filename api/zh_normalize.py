"""繁体标识符归一化 — 只服务于协议标记的识别，不改写模型原文。

存在的理由：描述符格式的工具调用标记（``[Edit开始]`` / ``[file_path参数]`` /
``[压缩结束]``）是简体中文字面量，而解析器用精确字符串比较识别它们。部分模型在
中文语境下会下意识写出繁体，于是 ``[Edit開始]`` 既不匹配开始标记、也不落入任何
其他分支，整段工具调用被当作普通正文。**这是一次静默失败**：没有报错，用户看到
的是「模型写了工具调用但没有出现可采纳的块」，而那个表象最像是模型没听懂格式。

三条设计约束，都不是风格偏好：

1. **繁简在这批字符上是严格 1:1 的字符映射，因此转换不改变字符串长度。**
   这是必需条件而非巧合：``response.py`` 的描述符解析器靠 ``_dline_starts``
   算出的偏移对 ``clean_content`` 做切片（``_dstart`` / ``_dend``），长度一变
   切片就错位，会把工具调用的一部分留在正文里、或把正文吞进参数里。任何往
   ``_TRAD_TO_SIMP`` 里加多字词映射的改动都会破坏这个前提。

2. **只对「用于判断这一行是不是标记」的副本调用本模块，参数值一律保持原样。**
   ``Edit`` 的 ``old_string``、``Write`` 的 ``content`` 里完全可能本来就含繁体
   （用户自己的代码注释、文档、引用的原文），转成简体会让查找替换失败——而那个
   失败看起来像是模型抄错了原文，排查方向会完全跑偏。

3. **字符表是封闭且可逐一审计的集合，刻意不引入 opencc 之类的库。**
   需要覆盖的字符就是标记词与工具名里出现的那些，数得清；而引入一个第三方依赖
   来修协议解析，等于制造一个新的「依赖没装好时工具调用静默失效」，那正是本模块
   要消除的同一类故障。

模型原文一字不动：``target_msg['content']`` 存的仍然是模型写的繁体文本，
归一化只发生在比较的那一瞬间。这与项目「你看得到 AI 看到的一切」的前提一致。
"""

# 繁体 → 简体，逐字。分组按用途注释，便于新增工具名时确认字符是否已覆盖。
#
# 一简对多繁的方向在这里是安全的：我们只做繁→简，而目标简体字是协议里已固定的
# 那一个，不存在歧义。反方向（简→繁）才有歧义，本模块刻意不提供。
_TRAD_TO_SIMP = {
    # 标记词本身：开始 / 结束 / 参数 / 立即 / 计划
    '開': '开', '結': '结', '參': '参', '數': '数',
    '計': '计', '劃': '划', '畫': '划',
    # 概括区块：概括开头 / 概括结尾
    '頭': '头',
    # 工具名用字：自动审稿、压缩、单关卡审稿、展开气泡、命名会话、
    # 创建子会话、结束子会话、申请审批、缩减读取
    '動': '动', '審': '审', '壓': '压', '縮': '缩',
    '單': '单', '關': '关', '氣': '气', '會': '会',
    '話': '话', '創': '创', '請': '请', '減': '减', '讀': '读',
}

# str.translate 走 C 实现，逐字符 dict 查找的开销在这里可以忽略。
_TRANS_TABLE = str.maketrans(_TRAD_TO_SIMP)


def to_simplified(text):
    """把协议标记里可能出现的繁体字换成简体。长度保持不变。

    对已是简体的输入是恒等变换，因此调用方不需要先判断。
    """
    if not text:
        return text
    return text.translate(_TRANS_TABLE)